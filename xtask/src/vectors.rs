//! `cargo xtask vectors fetch|lock`: test-vector sets at pinned commits, verified by hash.
//!
//! The sets are too large to commit. Each is a directory entry in `tests/assets/MANIFEST.toml`
//! with `fetch = true`, a `source_url` and a `commit`. `lock` downloads each set at its commit
//! and writes every file's SHA-256 to `tests/assets/vectors.lock`, which is committed. `fetch`
//! downloads a set only when the files present do not already match the lock, then verifies
//! them against it.
//!
//! The lock file holds one record per line, three fields separated by single spaces:
//!
//! ```text
//! commit <40 hex digits> <set path, relative to tests/assets/, ending in />
//! sha256 <64 hex digits> <file path, relative to tests/assets/>
//! ```

use std::{collections::BTreeMap, fmt::Write as _, fs, path::Path, process::Command};

use anyhow::{Context, Result, bail};

use crate::{
    finding::Finding,
    provenance::assets::{self, ASSETS, Asset, Manifest},
};

/// The lock file, relative to the workspace root.
pub(crate) const LOCK: &str = "tests/assets/vectors.lock";

const HEADER: &str = "\
# Generated by `cargo xtask vectors lock`; do not edit.
# commit <commit> <set path>: the commit a set was locked at.
# sha256 <hash> <file path>: one fetched file. Paths are relative to tests/assets/.
";

/// A vector set that is downloaded, not committed.
#[derive(Clone, Debug, Eq, PartialEq)]
pub(crate) struct FetchedSet {
    /// Directory relative to `tests/assets/`, ending in `/`.
    pub(crate) path: String,
    /// The `https://` URL of the git repository.
    pub(crate) source_url: String,
    /// The pinned commit, 40 hex digits.
    pub(crate) commit: String,
}

impl FetchedSet {
    /// The last component of the path: `65816` for `vectors/65816/`.
    fn name(&self) -> &str {
        let trimmed = self.path.trim_end_matches('/');
        trimmed.rsplit('/').next().unwrap_or(trimmed)
    }
}

/// The manifest's well-formed fetched directory entries. Malformed ones are reported by
/// `cargo xtask provenance assets` and skipped here.
pub(crate) fn sets(manifest: &Manifest) -> Vec<FetchedSet> {
    manifest
        .assets
        .iter()
        .filter_map(|asset| {
            let Asset {
                path,
                license: _,
                source_url,
                commit,
                sha256: _,
                fetch,
                notes: _,
            } = asset;
            let source_url = source_url.as_deref().filter(|url| is_source_url(url))?;
            let commit = commit.as_deref().filter(|commit| is_commit(commit))?;
            (*fetch && path.ends_with('/')).then(|| FetchedSet {
                path: path.clone(),
                source_url: String::from(source_url),
                commit: String::from(commit),
            })
        })
        .collect::<Vec<_>>()
}

/// Whether `url` may be handed to `git fetch`: HTTPS only, and never read as an option.
pub(crate) fn is_source_url(url: &str) -> bool {
    url.starts_with("https://") && !url.contains(char::is_whitespace)
}

/// Whether `commit` is a full lower-case SHA-1 commit id.
pub(crate) fn is_commit(commit: &str) -> bool {
    is_lower_hex(commit, 40)
}

fn is_lower_hex(text: &str, length: usize) -> bool {
    text.len() == length
        && text
            .bytes()
            .all(|byte| byte.is_ascii_digit() || (b'a'..=b'f').contains(&byte))
}

/// The parsed lock file.
#[derive(Clone, Debug, Default, Eq, PartialEq)]
pub(crate) struct Lock {
    /// The commit each set was locked at, keyed by set path.
    commits: BTreeMap<String, String>,
    /// The SHA-256 of each fetched file, keyed by path relative to `tests/assets/`.
    files: BTreeMap<String, String>,
}

impl Lock {
    /// Reads the lock file; a missing file is an empty lock.
    pub(crate) fn load(root: &Path) -> Result<Self> {
        let path = root.join(LOCK);
        if !path.is_file() {
            return Ok(Self::default());
        }
        let text = fs::read_to_string(&path).with_context(|| format!("reading {LOCK}"))?;
        Self::parse(&text).with_context(|| format!("parsing {LOCK}"))
    }

    fn parse(text: &str) -> Result<Self> {
        let mut lock = Self::default();
        for (index, line) in text.lines().enumerate() {
            let number = index + 1;
            if line.is_empty() || line.starts_with('#') {
                continue;
            }
            let fields = line.splitn(3, ' ').collect::<Vec<_>>();
            let previous = match fields.as_slice() {
                ["commit", commit, path] if is_commit(commit) && path.ends_with('/') => lock
                    .commits
                    .insert(String::from(*path), String::from(*commit)),
                ["sha256", hash, path] if is_lower_hex(hash, 64) && !path.ends_with('/') => {
                    lock.files.insert(String::from(*path), String::from(*hash))
                }
                _ => {
                    bail!("line {number}: expected `commit <id> <set>/` or `sha256 <hash> <file>`")
                }
            };
            if previous.is_some() {
                bail!("line {number}: duplicate path");
            }
        }
        Ok(lock)
    }

    fn render(&self) -> String {
        let Self { commits, files } = self;
        let mut text = String::from(HEADER);
        for (path, commit) in commits {
            // Writing to a `String` cannot fail.
            let _ = writeln!(text, "commit {commit} {path}");
        }
        for (path, hash) in files {
            let _ = writeln!(text, "sha256 {hash} {path}");
        }
        text
    }

    /// Replaces everything recorded for `set` with `present`.
    fn replace(&mut self, set: &FetchedSet, present: Vec<(String, String)>) {
        self.files.retain(|path, _| !path.starts_with(&set.path));
        self.files.extend(present);
        self.commits.insert(set.path.clone(), set.commit.clone());
    }

    /// Drops everything recorded for sets that are not in `sets`.
    fn retain_sets(&mut self, sets: &[FetchedSet]) {
        let known = |path: &str| sets.iter().any(|set| path.starts_with(&set.path));
        self.commits.retain(|path, _| known(path));
        self.files.retain(|path, _| known(path));
    }
}

/// Checks the files of one set against the lock. `present` holds `(path relative to
/// tests/assets, SHA-256 hex)`; entries outside the set are ignored. With `complete`, every
/// locked file of the set must be present.
pub(crate) fn verify_set(
    set: &FetchedSet,
    lock: &Lock,
    present: &[(String, String)],
    complete: bool,
) -> Vec<Finding> {
    let relock = "run `cargo xtask vectors lock` and commit the result";
    match lock.commits.get(&set.path) {
        None => {
            let message = format!("no entries for `{}`; {relock}", set.path);
            return vec![Finding::new(LOCK, 0, message)];
        }
        Some(locked) if *locked != set.commit => {
            let message = format!(
                "`{}` is locked at {locked}, the manifest pins {}; {relock}",
                set.path, set.commit
            );
            return vec![Finding::new(LOCK, 0, message)];
        }
        Some(_) => {}
    }
    let mut findings = Vec::new();
    let in_set = present
        .iter()
        .filter(|(path, _)| path.starts_with(&set.path));
    for (path, hash) in in_set {
        match lock.files.get(path) {
            None => findings.push(Finding::new(
                format!("{ASSETS}/{path}"),
                0,
                format!("fetched file is not in {LOCK}"),
            )),
            Some(expected) if expected != hash => findings.push(Finding::new(
                format!("{ASSETS}/{path}"),
                0,
                format!("SHA-256 is {hash}, {LOCK} says {expected}"),
            )),
            Some(_) => {}
        }
    }
    if complete {
        let locked = lock.files.keys().filter(|path| path.starts_with(&set.path));
        for path in locked {
            if !present.iter().any(|(present_path, _)| present_path == path) {
                findings.push(Finding::new(
                    format!("{ASSETS}/{path}"),
                    0,
                    "locked file is missing; run `cargo xtask vectors fetch`",
                ));
            }
        }
    }
    findings
}

/// Lock records that belong to no set in the manifest.
pub(crate) fn stale_records(sets: &[FetchedSet], lock: &Lock) -> Vec<Finding> {
    let known = |path: &str| sets.iter().any(|set| path.starts_with(&set.path));
    lock.commits
        .keys()
        .chain(lock.files.keys())
        .filter(|path| !known(path))
        .map(|path| {
            let message = format!("`{path}` belongs to no fetched set in the manifest");
            Finding::new(LOCK, 0, message)
        })
        .collect::<Vec<_>>()
}

/// `cargo xtask vectors fetch [set]`.
pub(crate) fn fetch(root: &Path, only: Option<&str>) -> Result<Vec<Finding>> {
    let manifest = Manifest::load(root)?;
    let selected = select(sets(&manifest), only)?;
    let lock = Lock::load(root)?;
    let assets_directory = root.join(ASSETS);
    let mut findings = Vec::new();
    for set in &selected {
        let directory = assets_directory.join(&set.path);
        let present = assets::hash_tree(&assets_directory, &directory)?;
        let mut problems = verify_set(set, &lock, &present, true);
        if problems.is_empty() {
            println!("{}: up to date ({} files)", set.path, present.len());
        } else {
            download(set, &directory)?;
            let present = assets::hash_tree(&assets_directory, &directory)?;
            problems = verify_set(set, &lock, &present, true);
        }
        findings.extend(problems);
    }
    Ok(findings)
}

/// `cargo xtask vectors lock [set]`. Always downloads, so the lock records what the pinned
/// commit holds and not whatever is in the working tree.
pub(crate) fn lock(root: &Path, only: Option<&str>) -> Result<Vec<Finding>> {
    let manifest = Manifest::load(root)?;
    let all = sets(&manifest);
    let selected = select(all.clone(), only)?;
    let mut lock = Lock::load(root)?;
    lock.retain_sets(&all);
    let assets_directory = root.join(ASSETS);
    for set in &selected {
        let directory = assets_directory.join(&set.path);
        download(set, &directory)?;
        let present = assets::hash_tree(&assets_directory, &directory)?;
        println!("{}: locked {} files", set.path, present.len());
        lock.replace(set, present);
    }
    fs::write(root.join(LOCK), lock.render()).with_context(|| format!("writing {LOCK}"))?;
    Ok(Vec::new())
}

fn select(sets: Vec<FetchedSet>, only: Option<&str>) -> Result<Vec<FetchedSet>> {
    let Some(name) = only else {
        return Ok(sets);
    };
    let names = sets
        .iter()
        .map(FetchedSet::name)
        .collect::<Vec<_>>()
        .join(", ");
    let selected = sets
        .iter()
        .filter(|set| set.name() == name)
        .cloned()
        .collect::<Vec<_>>();
    if selected.is_empty() {
        bail!("no fetched set named `{name}` in the manifest (sets: {names})");
    }
    Ok(selected)
}

/// Replaces `directory` with the set's files at its pinned commit, using a shallow `git` fetch
/// of that one commit. The temporary repository is removed afterwards.
fn download(set: &FetchedSet, directory: &Path) -> Result<()> {
    let FetchedSet {
        path,
        source_url,
        commit,
    } = set;
    println!("{path}: fetching {commit} from {source_url}");
    if directory.exists() {
        fs::remove_dir_all(directory).with_context(|| format!("removing {path}"))?;
    }
    fs::create_dir_all(directory).with_context(|| format!("creating {path}"))?;
    git(directory, &["init", "--quiet"])?;
    git(directory, &["fetch", "--depth", "1", source_url, commit])?;
    git(
        directory,
        &["checkout", "--quiet", "--detach", "FETCH_HEAD"],
    )?;
    fs::remove_dir_all(directory.join(".git"))
        .with_context(|| format!("removing the temporary repository in {path}"))
}

/// Runs `git` in `directory` with line-ending conversion off, so file hashes are the same on
/// every platform.
fn git(directory: &Path, arguments: &[&str]) -> Result<()> {
    let status = Command::new("git")
        .current_dir(directory)
        .args([
            "-c",
            "core.autocrlf=false",
            "-c",
            "advice.detachedHead=false",
        ])
        .args(arguments)
        .status()
        .context("running git (is it installed?)")?;
    if !status.success() {
        bail!("`git {}` failed: {status}", arguments.join(" "));
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    const COMMIT: &str = "307c63f5673c8c6b861c52f71ddb89212a227480";
    const OTHER_COMMIT: &str = "67d15f492b2740964abd4efd1229e0ec9c342228";

    fn set() -> FetchedSet {
        FetchedSet {
            path: String::from("vectors/65816/"),
            source_url: String::from("https://example.org/65816"),
            commit: String::from(COMMIT),
        }
    }

    fn hash(digit: char) -> String {
        String::from(digit).repeat(64)
    }

    fn present(entries: &[(&str, char)]) -> Vec<(String, String)> {
        entries
            .iter()
            .map(|(path, digit)| (String::from(*path), hash(*digit)))
            .collect::<Vec<_>>()
    }

    fn locked(entries: &[(&str, char)]) -> Lock {
        let mut lock = Lock::default();
        lock.replace(&set(), present(entries));
        lock
    }

    fn messages(findings: Vec<Finding>) -> Vec<String> {
        findings
            .into_iter()
            .map(|finding| finding.to_string())
            .collect::<Vec<_>>()
    }

    #[test]
    fn lock_round_trips() {
        let lock = locked(&[
            ("vectors/65816/v1/00.e.json", 'a'),
            ("vectors/65816/a b", 'b'),
        ]);
        let text = lock.render();
        assert!(text.contains(&format!("commit {COMMIT} vectors/65816/\n")));
        assert_eq!(Lock::parse(&text).unwrap(), lock);
    }

    #[test]
    fn malformed_lock_lines_are_rejected() {
        let short = "sha256 abc vectors/65816/x\n";
        let unknown = format!("md5 {} vectors/65816/x\n", hash('a'));
        let directory = format!("sha256 {} vectors/65816/\n", hash('a'));
        let duplicate = format!("commit {COMMIT} a/\ncommit {COMMIT} a/\n");
        for text in [
            short,
            unknown.as_str(),
            directory.as_str(),
            duplicate.as_str(),
        ] {
            assert!(Lock::parse(text).is_err(), "{text}");
        }
    }

    #[test]
    fn matching_files_pass() {
        let files = [("vectors/65816/00", 'a'), ("vectors/65816/01", 'b')];
        let lock = locked(&files);
        assert_eq!(verify_set(&set(), &lock, &present(&files), true), vec![]);
        // A partial set passes unless completeness is asked for; other sets are ignored.
        let partial = present(&[("vectors/65816/00", 'a'), ("vectors/spc700/00", 'c')]);
        assert_eq!(verify_set(&set(), &lock, &partial, false), vec![]);
    }

    #[test]
    fn differences_are_reported() {
        let lock = locked(&[("vectors/65816/00", 'a'), ("vectors/65816/01", 'b')]);
        let files = present(&[("vectors/65816/00", 'c'), ("vectors/65816/02", 'd')]);
        let found = messages(verify_set(&set(), &lock, &files, true));
        assert_eq!(found.len(), 3, "{found:?}");
        assert!(found[0].contains("SHA-256"));
        assert!(found[1].contains("not in"));
        assert!(found[2].contains("missing"));
    }

    #[test]
    fn unlocked_or_repinned_sets_are_reported() {
        let files = present(&[("vectors/65816/00", 'a')]);
        let unlocked = messages(verify_set(&set(), &Lock::default(), &files, false));
        assert_eq!(unlocked.len(), 1, "{unlocked:?}");
        assert!(unlocked[0].contains("no entries"));

        let mut repinned = set();
        repinned.commit = String::from(OTHER_COMMIT);
        let lock = locked(&[("vectors/65816/00", 'a')]);
        let found = messages(verify_set(&repinned, &lock, &files, false));
        assert_eq!(found.len(), 1, "{found:?}");
        assert!(found[0].contains("locked at"));
    }

    #[test]
    fn stale_records_are_reported_and_dropped() {
        let mut lock = locked(&[("vectors/65816/00", 'a')]);
        assert_eq!(stale_records(&[set()], &lock), vec![]);
        assert_eq!(stale_records(&[], &lock).len(), 2);
        lock.retain_sets(&[]);
        assert_eq!(lock, Lock::default());
    }

    #[test]
    fn sets_come_from_fetched_directory_entries() {
        let text = format!(
            "[[asset]]\npath = \"vectors/65816/\"\nlicense = \"MIT\"\nfetch = true\n\
             source_url = \"https://example.org/65816\"\ncommit = \"{COMMIT}\"\n\n\
             [[asset]]\npath = \"golden/\"\nlicense = \"own\"\n\n\
             [[asset]]\npath = \"bad/\"\nlicense = \"MIT\"\nfetch = true\n\
             source_url = \"--upload-pack=x\"\ncommit = \"{COMMIT}\"\n"
        );
        let manifest = toml::from_str::<Manifest>(&text).unwrap();
        assert_eq!(sets(&manifest), vec![set()]);
        assert_eq!(set().name(), "65816");
        assert!(select(vec![set()], Some("spc700")).is_err());
        assert_eq!(select(vec![set()], Some("65816")).unwrap(), vec![set()]);
    }
}
